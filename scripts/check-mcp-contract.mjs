import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const fail = msg => { throw new Error(`MCP contract check failed: ${msg}`); };
const core = fs.readFileSync(path.join(ROOT, 'mcp/core.mjs'), 'utf8');
const stdio = fs.readFileSync(path.join(ROOT, 'mcp/server.mjs'), 'utf8');
const remote = fs.readFileSync(path.join(ROOT, 'mcp/remote.mjs'), 'utf8');
const tools = ['search_knowledge','get_hack','get_protocol','get_evidence','list_topics','get_related'];
for (const tool of tools) if (!core.includes(`registerTool('${tool}'`)) fail(`missing tool ${tool}`);
if (!core.includes("['pending-review', 'restricted']") || !core.includes('trustedOnly')) fail('trust-state filtering is missing');
if (!core.includes('safetySensitive') || !core.includes('found: false')) fail('no-answer or missing-ID behavior is not explicit');
if (!stdio.includes('serveStdio') || !stdio.includes('createBraliServer')) fail('stdio transport must use the shared factory');
if (!remote.includes('createMcpHandler') || !remote.includes('createBraliServer')) fail('remote transport must use the official HTTP entry and shared factory');
if (!remote.includes('DEFAULT_DATA_ORIGIN') || !remote.includes('https://brali-lifeos.github.io/api/v1')) fail('remote source must use the canonical API by default');
if (/registerTool\(/.test(remote) || /registerTool\(/.test(stdio)) fail('transport files must not fork MCP tool semantics');
const search = JSON.parse(fs.readFileSync(path.join(ROOT, 'api/v1/search.json'), 'utf8')).items || [];
const focus = search.filter(item => /focus|attention/i.test(`${item.title || ''} ${item.search_text || ''}`));
if (!focus.some(item => item.id === 'brali:topic:attention-focus')) fail('representative focus query cannot resolve attention-focus');
const ids = new Set(search.map(item => item.id));
if (ids.has('brali:protocol:definitely-missing')) fail('missing-ID fixture unexpectedly exists');
const api = JSON.parse(fs.readFileSync(path.join(ROOT, 'api/v1/index.json'), 'utf8'));
if (!api.endpoints?.includes('evidence.json') || !api.endpoints?.includes('identity.json')) fail('MCP backing API is incomplete');
console.log(`MCP contract check passed: ${tools.length} tools share stdio/HTTP semantics; representative retrieval, missing-ID, safety and trust behavior verified`);
